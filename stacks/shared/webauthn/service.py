"""WebAuthn server-side ceremonies for BankShield HumanGate (Python).

``WebAuthnService`` implements the four ceremonies against a relying
party id and origin passed in by the caller (no hardcoded production
origin):

- ``begin_registration`` / ``finish_registration``
- ``begin_authentication`` / ``finish_authentication``

Challenges are generated by the library, stored in memory, and consumed
on first use: verifying the same response twice fails, which is what
makes a replayed challenge fail. Production must also give challenges
an expiry (for example a short TTL in Redis); this in-memory holder
does not expire them.

Attestation: the library verifies attestation statements for the
formats it supports (``packed``, ``tpm``, ``android-key``,
``android-safetynet``, ``fido-u2f``, ``apple``, ``none``). The
verification result records the attestation format and the trust path.
By default no root certificates are pinned: verification uses the
library default, which for ``fmt="none"`` means there is no attestation
statement and no trust path at all. Production must pin to a trusted
attestation authority list (pass ``pem_root_certs_by_fmt``) instead of
relying on the library default. See ``README.md`` in this directory.
"""
from __future__ import annotations

import json
import os
import sys
from dataclasses import dataclass


class WebAuthnError(Exception):
    """Base error for WebAuthn ceremony failures."""


class ChallengeNotFoundError(WebAuthnError):
    """No live challenge for this user and ceremony.

    Raised when a challenge was already consumed, never issued, or
    expired. A replayed challenge therefore fails here, before any
    cryptographic check runs.
    """


class VerificationFailedError(WebAuthnError):
    """The authenticator response did not verify (bad signature, wrong
    origin, wrong relying party, unknown credential, or a sign count
    that did not advance)."""


def _load_webauthn_library():
    """Load the installed ``webauthn`` library despite this package
    sharing its name.

    This package lives in a directory named ``webauthn``, so when
    ``stacks/shared`` is on ``sys.path`` this package shadows the PyPI
    library of the same name. If the module already in ``sys.modules``
    under ``"webauthn"`` is the real library (it has
    ``verify_registration_response``), use it. Otherwise swap this
    package out of ``sys.modules``, drop this package's parent
    directory from ``sys.path`` so the finder reaches site-packages,
    import the real library, then restore both. The real library's
    submodules stay registered in ``sys.modules`` under their
    ``webauthn.*`` names, which is what its own absolute imports need.
    """
    existing = sys.modules.get("webauthn")
    if existing is not None and hasattr(existing, "verify_registration_response"):
        return existing
    ours = sys.modules.pop("webauthn", None)
    local_parent = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    # Drop every sys.path entry that resolves to this package's parent
    # directory (the absolute path, and "" which means the current
    # working directory when it is that directory), so the finder
    # reaches site-packages instead of finding this package again.
    removed_paths = []
    kept_paths = []
    for entry in sys.path:
        resolved = os.path.abspath(entry) if entry else os.getcwd()
        if resolved == local_parent:
            removed_paths.append(entry)
        else:
            kept_paths.append(entry)
    if removed_paths:
        sys.path[:] = kept_paths
    try:
        import webauthn as real  # noqa: F401  (resolved from site-packages)
    except ImportError as exc:
        raise ImportError(
            "The 'webauthn' library (PyPI package 'webauthn', version 3.x) "
            "is not installed. Install it first, for example with "
            "'pip install -r stacks/shared/webauthn/requirements.txt' "
            "inside a virtual environment. The gate itself has no "
            "dependencies; only this WebAuthn package needs the library."
        ) from exc
    finally:
        if ours is not None:
            sys.modules["webauthn"] = ours
        if removed_paths:
            sys.path[:] = removed_paths + sys.path
    if not hasattr(real, "verify_registration_response"):
        raise ImportError(
            "Found a 'webauthn' module that is not the py_webauthn library "
            "(it has no verify_registration_response). Check sys.path."
        )
    return real


_lib = _load_webauthn_library()


@dataclass
class VerifiedRegistrationResult:
    verified: bool = True
    credential_id: bytes = b""
    public_key: bytes = b""
    sign_count: int = 0
    attestation_format: str = "none"
    aaguid: str = ""
    credential_device_type: str = ""
    credential_backed_up: bool = False
    user_verified: bool = False
    # Human-readable record of how the attestation was trusted.
    trust_path: str = "none (no attestation statement, no trust path)"


@dataclass
class VerifiedAuthenticationResult:
    verified: bool = True
    credential_id: bytes = b""
    new_sign_count: int = 0
    credential_device_type: str = ""
    credential_backed_up: bool = False
    user_verified: bool = False


class WebAuthnService:
    """Server side of the WebAuthn registration and authentication
    ceremonies for one relying party.

    ``rp_id`` and ``origin`` come from the caller; there is no
    hardcoded production origin. ``store`` holds registered
    credentials; production replaces the in-memory store with a
    database-backed one implementing the same interface.
    """

    def __init__(
        self,
        rp_id: str,
        rp_name: str,
        origin: str,
        store,
        attestation: str = "none",
        require_user_verification: bool = False,
        pem_root_certs_by_fmt=None,
    ) -> None:
        if not rp_id or not origin:
            raise ValueError("rp_id and origin are required")
        self.rp_id = rp_id
        self.rp_name = rp_name
        self.origin = origin
        self.store = store
        self.attestation = attestation
        self.require_user_verification = require_user_verification
        self.pem_root_certs_by_fmt = pem_root_certs_by_fmt
        # (ceremony, user_id) -> challenge bytes. Single use: popped
        # by the matching finish_* call.
        self._challenges: dict = {}

    # -- registration -------------------------------------------------

    def begin_registration(self, user_id: bytes, user_name: str,
                           user_display_name: str | None = None):
        """Return (options_dict, challenge_bytes) for
        ``navigator.credentials.create()``. ``user_id`` is an opaque
        per-user byte identifier (never an email address in the clear
        unless the caller chooses so)."""
        exclude = [
            _lib.helpers.structs.PublicKeyCredentialDescriptor(
                id=record.credential_id,
                transports=list(record.transports) or None,
            )
            for record in self.store.list_for_user(user_id)
        ]
        options = _lib.generate_registration_options(
            rp_id=self.rp_id,
            rp_name=self.rp_name,
            user_id=user_id,
            user_name=user_name,
            user_display_name=user_display_name or user_name,
            attestation=_lib.helpers.structs.AttestationConveyancePreference(
                self.attestation
            ),
            exclude_credentials=exclude or None,
        )
        self._challenges[("registration", user_id)] = options.challenge
        return json.loads(_lib.options_to_json(options)), options.challenge

    def finish_registration(self, user_id: bytes, credential):
        """Verify a ``navigator.credentials.create()`` response and
        store the credential. Returns a ``VerifiedRegistrationResult``
        recording the attestation format and trust path. Raises
        ``ChallengeNotFoundError`` if the challenge was already used
        and ``VerificationFailedError`` if the response does not
        verify."""
        challenge = self._challenges.pop(("registration", user_id), None)
        if challenge is None:
            raise ChallengeNotFoundError(
                "no live registration challenge for this user; the "
                "challenge was already used, never issued, or expired"
            )
        try:
            verified = _lib.verify_registration_response(
                credential=credential,
                expected_challenge=challenge,
                expected_rp_id=self.rp_id,
                expected_origin=self.origin,
                require_user_verification=self.require_user_verification,
                pem_root_certs_bytes_by_fmt=self.pem_root_certs_by_fmt,
            )
        except Exception as exc:
            raise VerificationFailedError(
                f"registration response did not verify: {exc}"
            ) from exc
        fmt = str(getattr(verified, "fmt", "none"))
        if self.pem_root_certs_by_fmt:
            trust_path = (
                f"{fmt} attestation verified against caller-supplied "
                "root certificates (pinned attestation authority list)"
            )
        elif fmt == "none":
            trust_path = "none (no attestation statement, no trust path)"
        else:
            trust_path = (
                f"{fmt} attestation verified against the library "
                "default trust roots; no pinned production attestation "
                "authority list was configured"
            )
        result = VerifiedRegistrationResult(
            verified=True,
            credential_id=verified.credential_id,
            public_key=verified.credential_public_key,
            sign_count=verified.sign_count,
            attestation_format=fmt,
            aaguid=str(getattr(verified, "aaguid", "")),
            credential_device_type=str(
                getattr(verified, "credential_device_type", "")
            ),
            credential_backed_up=bool(
                getattr(verified, "credential_backed_up", False)
            ),
            user_verified=bool(getattr(verified, "user_verified", False)),
            trust_path=trust_path,
        )
        from .store import CredentialRecord

        self.store.save(
            CredentialRecord(
                credential_id=result.credential_id,
                user_id=user_id,
                public_key=result.public_key,
                sign_count=result.sign_count,
                transports=tuple(
                    (credential.get("transports") or [])
                    if isinstance(credential, dict)
                    else []
                ),
                attestation_format=result.attestation_format,
                aaguid=result.aaguid,
                credential_device_type=result.credential_device_type,
                credential_backed_up=result.credential_backed_up,
            )
        )
        return result

    # -- authentication -----------------------------------------------

    def begin_authentication(self, user_id: bytes):
        """Return (options_dict, challenge_bytes) for
        ``navigator.credentials.get()``. The options allow only this
        user's registered credentials; if the user has none, the
        allow list is empty and the client may offer any credential."""
        allow = [
            _lib.helpers.structs.PublicKeyCredentialDescriptor(
                id=record.credential_id,
                transports=list(record.transports) or None,
            )
            for record in self.store.list_for_user(user_id)
        ]
        options = _lib.generate_authentication_options(
            rp_id=self.rp_id,
            allow_credentials=allow or None,
        )
        self._challenges[("authentication", user_id)] = options.challenge
        return json.loads(_lib.options_to_json(options)), options.challenge

    def finish_authentication(self, user_id: bytes, credential):
        """Verify a ``navigator.credentials.get()`` response. Returns
        a ``VerifiedAuthenticationResult`` and advances the stored
        sign count. Raises ``ChallengeNotFoundError`` on a replayed
        challenge and ``VerificationFailedError`` on any other
        verification failure, including a sign count that did not
        advance (cloned authenticator)."""
        challenge = self._challenges.pop(("authentication", user_id), None)
        if challenge is None:
            raise ChallengeNotFoundError(
                "no live authentication challenge for this user; the "
                "challenge was already used, never issued, or expired"
            )
        credential_id = self._credential_id_from_response(credential)
        record = self.store.get(credential_id) if credential_id else None
        if record is None:
            raise VerificationFailedError("unknown credential id")
        try:
            verified = _lib.verify_authentication_response(
                credential=credential,
                expected_challenge=challenge,
                expected_rp_id=self.rp_id,
                expected_origin=self.origin,
                credential_public_key=record.public_key,
                credential_current_sign_count=record.sign_count,
                require_user_verification=self.require_user_verification,
            )
        except Exception as exc:
            raise VerificationFailedError(
                f"authentication response did not verify: {exc}"
            ) from exc
        if record.sign_count > 0 and verified.new_sign_count <= record.sign_count:
            raise VerificationFailedError(
                "sign count did not advance; the authenticator may be "
                "cloned (replayed assertion)"
            )
        self.store.update_sign_count(credential_id, verified.new_sign_count)
        return VerifiedAuthenticationResult(
            verified=True,
            credential_id=verified.credential_id,
            new_sign_count=verified.new_sign_count,
            credential_device_type=str(
                getattr(verified, "credential_device_type", "")
            ),
            credential_backed_up=bool(
                getattr(verified, "credential_backed_up", False)
            ),
            user_verified=bool(getattr(verified, "user_verified", False)),
        )

    @staticmethod
    def _credential_id_from_response(credential):
        try:
            if isinstance(credential, dict):
                raw_id = credential.get("rawId") or credential.get("id")
            elif isinstance(credential, str):
                raw_id = json.loads(credential).get("rawId")
            else:
                raw_id = getattr(credential, "raw_id", None) or getattr(
                    credential, "id", None
                )
            if raw_id is None:
                return None
            if isinstance(raw_id, (bytes, bytearray)):
                return bytes(raw_id)
            return _lib.base64url_to_bytes(raw_id)
        except Exception:
            return None
